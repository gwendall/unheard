// pnpm scoreboard: rewrites the README's scoreboard (between its markers) from the counts the
// evals committed in evals/results.json. Run it after `pnpm eval` changed results.json.
// `--check` only says whether the README is current (exit 1 when it is not).

import { readFileSync, writeFileSync } from "node:fs";
import { rate } from "../evals/lib/stats.ts";

type Counts = {
  heard: { n: number; strongHit: number; anyHit: number; wrongStrong: number; wrongPossible: number };
  empty: { n: number; falseStrong: number; falsePossible: number };
  date: string;
};

/** The order of the rows, and what each eval runs on. */
const EVALS: [string, string][] = [
  ["synthetic", "made-up flybys, faint on purpose, with clock error, wind and noisy ADS-B"],
  ["real-tracks", "real adsb.lol tracks (Phoenix), made-up sound"],
  ["real-audio", "AeroSonicDB (Adelaide) and phone recordings (Livermore, California), real sound and ADS-B; run locally, data not in git"],
];

const START = "<!-- scoreboard:start -->";
const END = "<!-- scoreboard:end -->";
const readme = new URL("../README.md", import.meta.url);
const results = JSON.parse(readFileSync(new URL("../evals/results.json", import.meta.url), "utf8")) as Record<string, Counts>;

const rows = EVALS.filter(([name]) => results[name]).map(([name, data]) => {
  const r = results[name];
  return `| ${name} | ${data} | ${rate(r.heard.strongHit, r.heard.n)} | ${rate(r.heard.anyHit, r.heard.n)} | ${rate(r.heard.wrongStrong, r.heard.n)} | ${r.empty.n ? rate(r.empty.falseStrong, r.empty.n) : "none in this set"} |`;
});
const dates = EVALS.map(([name]) => results[name]?.date).filter(Boolean).sort();
const block = [
  START,
  "| Eval | Data | Sure and right | Named and right | Sure but wrong | Sure with nothing to find |",
  "|---|---|---|---|---|---|",
  ...rows,
  "",
  `Counts with 95 % intervals (Wilson); "sure" is the page's "It was X", "named" adds "possibly X". Last change ${dates[dates.length - 1]}. Generated by \`pnpm scoreboard\` from \`evals/results.json\`.`,
  END,
].join("\n");

const text = readFileSync(readme, "utf8");
const from = text.indexOf(START);
const to = text.indexOf(END);
if (from < 0 || to < from) throw new Error(`README.md has no ${START} ... ${END} block`);
const next = text.slice(0, from) + block + text.slice(to + END.length);

if (process.argv.includes("--check")) {
  if (next !== text) {
    console.error("README.md scoreboard is stale: run pnpm scoreboard");
    process.exit(1);
  }
  console.log("README.md scoreboard is current");
} else {
  writeFileSync(readme, next);
  console.log(next === text ? "README.md scoreboard unchanged" : "README.md scoreboard updated");
}
