export function aircraftType(code?: string): { name: string; kind: Kind | null } | null {
  if (!code) return null;
  const hit = T[code.toUpperCase()];
  return hit ? { name: hit[0], kind: hit[1] } : { name: code.toUpperCase(), kind: null };
}

/** Whether this aircraft has the kind of sound the matcher reads best: a propeller or a rotor. */
export function isTonal(code?: string, category?: string): boolean | null {
  if (category === "A7") return true;
  const kind = code ? T[code.toUpperCase()]?.[1] : undefined;
  if (kind) return kind !== "jet";
  if (category === "A1") return true;
  return null;
}
